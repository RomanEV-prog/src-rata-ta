-- Cenik (stran /ceniki) — postavke, ki jih osebje ureja v /admin/cenik.
-- Paketi streljanja so posebej v tabeli `packages` (/admin/paketi).
-- Idempotentno: varno pognati večkrat.

create table if not exists public.price_items (
  id          bigint generated by default as identity primary key,
  section     text    not null,
  title       text    not null,
  subtitle    text,
  price       numeric,
  unit        text,
  sort_order  integer not null default 0,
  is_active   boolean not null default true,
  updated_at  bigint
);

alter table public.price_items enable row level security;

drop policy if exists price_items_public_read on public.price_items;
create policy price_items_public_read on public.price_items
  for select to anon, authenticated using (is_active or auth.role() = 'authenticated');

drop policy if exists price_items_auth_insert on public.price_items;
create policy price_items_auth_insert on public.price_items
  for insert to authenticated with check (true);

drop policy if exists price_items_auth_update on public.price_items;
create policy price_items_auth_update on public.price_items
  for update to authenticated using (true) with check (true);

drop policy if exists price_items_auth_delete on public.price_items;
create policy price_items_auth_delete on public.price_items
  for delete to authenticated using (true);

grant select on public.price_items to anon;
grant select, insert, update, delete on public.price_items to authenticated;

